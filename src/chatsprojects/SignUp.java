    public void signUpUser() {

        email = jTextField1.getText().trim();
        String password = jTextField2.getText();

        if (email.isEmpty() || password.isEmpty()) {
            jLabel4.setText(
                    "Please enter your email and password."
            );
            return;
        }

        String sql
                = "INSERT INTO authusers (user_email, user_password) "
                + "VALUES (?, ?)";

        try (
                 Connection connection
                = DatabaseConnection.getConnection();  PreparedStatement statement
                = connection.prepareStatement(
                        sql,
                        Statement.RETURN_GENERATED_KEYS
                )) {
            statement.setString(1, email);
            statement.setString(2, password);

            int rowsInserted = statement.executeUpdate();

            if (rowsInserted > 0) {

                // Retrieve the newly generated database ID.
                try ( ResultSet keys = statement.getGeneratedKeys()) {
                    if (keys.next()) {
                        userID = keys.getInt(1);
                    }
                }

                if (userID > 0) {

                    System.out.println(
                            "New user ID: " + userID
                    );

                    JOptionPane.showMessageDialog(
                            this,
                            "Account created successfully!"
                    );

                    // Open the username setup screen.
                    SignUsername signUserPage
                            = new SignUsername();

                    signUserPage.setVisible(true);

                    this.dispose();

                } else {
                    JOptionPane.showMessageDialog(
                            this,
                            "Account created, but the ID "
                            + "could not be retrieved."
                    );
                }
            }

        } catch (SQLException e) {

            if (e.getErrorCode() == 1062) {
                jLabel4.setText(
                        "That email is already registered."
                );
            } else {
                JOptionPane.showMessageDialog(
                        this,
                        "Database error:\n" + e.getMessage()
                );

                e.printStackTrace();
            }
        }
    }

