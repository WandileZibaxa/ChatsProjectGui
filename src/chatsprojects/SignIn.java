    public void signInUser() {

        // In your form, jTextField1 is the email field
        // and jTextField2 is the password field.
        String email = jTextField1.getText().trim();
        String password = jTextField2.getText();

        if (email.isEmpty() || password.isEmpty()) {
            jLabel4.setText("Please enter your email and password.");
            return;
        }

        String sql
                = "SELECT id_user FROM authusers "
                + "WHERE user_email = ? AND user_password = ?";

        try (
                 Connection connection = DatabaseConnection.getConnection();  PreparedStatement statement = connection.prepareStatement(sql)) {

            statement.setString(1, email);
            statement.setString(2, password);

            try ( ResultSet result = statement.executeQuery()) {

                if (result.next()) {

                    // Save the ID of the logged-in account.
                    myID = result.getInt("id_user");

                    // Your authusers table does not need a name column.
                    myName = email;

                    System.out.println("Login successful!");
                    System.out.println("Logged in user ID: " + myID);

                    JOptionPane.showMessageDialog(
                            this,
                            "Login successful!"
                    );

                    // Open the Find Users window.
                    FindUsers myFriends = new FindUsers();
                    myFriends.setLocationRelativeTo(null);
                    myFriends.setVisible(true);

                    // Close the login window.
                    this.dispose();

                } else {

                    jLabel4.setText("Incorrect email or password.");
                }
            }

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Database error:\n" + e.getMessage(),
                    "Login Error",
                    JOptionPane.ERROR_MESSAGE
            );

            e.printStackTrace();
        }
    }
    
