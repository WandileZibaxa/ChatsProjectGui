    public void sendText() {
        String userText = jTextField1.getText();

        if (userText.isEmpty()) {

            System.out.print("Please enter your email and password.");

            return;
        }

        String sql
                = "INSERT INTO groupchats (auth_key, username, user_text) VALUES (?, ?, ?)";

        try (
                 Connection connection
                = DatabaseConnection.getConnection();  PreparedStatement statement
                = connection.prepareStatement(sql)) {

            statement.setString(1, userText);

            //statement.setString(2, password);
            statement.executeUpdate();

            JOptionPane.showMessageDialog(
                    this,
                    "Account created successfully!"
            );

            SignUsername signUserPage = new SignUsername();
            signUserPage.setVisible(true);

            this.dispose();

        } catch (SQLException e) {

            if (e.getMessage().contains("Duplicate")) {

                System.out.print("That email is already registered.");

            } else {

                JOptionPane.showMessageDialog(
                        this,
                        "Database error:\n" + e.getMessage()
                );

                e.printStackTrace();
            }
        }
    }
    
