    public void sendText(){
        String userText = jTextField1.getText().trim();

        if (userText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a message.");
            return;
        }

        if (SignIn.myID <= 0 || receiverId <= 0) {
            JOptionPane.showMessageDialog(
                    this,
                    "The sender or recipient could not be identified."
            );
            return;
        }

        String sql
                = "INSERT INTO chat_messages "
                + "(sender_id, receiver_id, message_text) "
                + "VALUES (?, ?, ?)";

        try (
                 Connection connection = DatabaseConnection.getConnection();  PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setInt(1, SignIn.myID);
            statement.setInt(2, receiverId);
            statement.setString(3, userText);

            statement.executeUpdate();

            jTextField1.setText("");

            loadMessages();

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(
                    this,
                    "Could not send message:\n" + e.getMessage(),
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }
    
    
